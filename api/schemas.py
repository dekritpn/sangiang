"""Pydantic schemas for FastAPI REST endpoints."""

from typing import List, Optional
from pydantic import BaseModel, Field


class TranslationRequest(BaseModel):
    text: str = Field(..., description="Text to translate (accepts input with or without diacritics)")
    direction: str = Field(
        default="sangihe_to_id",
        description="Translation direction: 'sangihe_to_id' or 'id_to_sangihe'",
    )
    model: Optional[str] = Field(default=None, description="Optional model override, e.g. 'qwen2.5-sangihe:7b'")
    temperature: float = Field(default=0.2, ge=0.0, le=1.0)
    top_k_parallel: int = Field(default=3, ge=0, le=10)
    max_lexical: int = Field(default=8, ge=0, le=20)


class LexicalContextItem(BaseModel):
    lemma_id: int
    lema_display: Optional[str] = ""
    lema_normalized: Optional[str] = ""
    summary_gloss: Optional[str] = ""
    match_source: Optional[str] = ""


class ParallelMatchItem(BaseModel):
    reference_id: str
    source_domain: str
    sangihe: str
    indonesian: str
    score: float


class TranslationResponse(BaseModel):
    input_text: str
    translated_text: str
    direction: str
    elapsed_ms: float
    model: str = ""
    diacritics_restored: bool
    lexical_entries: List[LexicalContextItem] = []
    parallel_matches: List[ParallelMatchItem] = []


class ModelInfo(BaseModel):
    name: str
    is_active: bool
    is_finetuned: bool


class ModelsResponse(BaseModel):
    active_model: str
    available_models: List[ModelInfo]


class MorphologyRequest(BaseModel):
    word: str = Field(..., description="Sangihe word to analyze")


class MorphologyResponse(BaseModel):
    surface: str
    normalized: str
    is_reduplicated: bool
    prefixes: List[str]
    infixes: List[str]
    suffixes: List[str]
    candidate_stems: List[str]


class DictionaryLookupRequest(BaseModel):
    query: str
    direction: str = "sangihe"  # "sangihe" or "indonesian"
    limit: int = 10


class HealthResponse(BaseModel):
    status: str
    ollama_connected: bool
    corpus_sentences_count: int
    lexical_database_available: bool


class FeedbackRequest(BaseModel):
    input_text: str = Field(..., description="Original source sentence")
    machine_translation: str = Field(..., description="Translation generated by Sangiang")
    direction: str = Field(default="sangihe_to_id", description="'sangihe_to_id' or 'id_to_sangihe'")
    is_correct: bool = Field(default=False, description="True if user confirmed the translation is accurate")
    corrected_translation: Optional[str] = Field(default="", description="User-provided corrected translation")
    notes: Optional[str] = Field(default="", description="Optional notes or explanation from the speaker")


class FeedbackResponse(BaseModel):
    status: str
    feedback_id: int
    message: str
